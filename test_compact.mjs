import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('./app.js',import.meta.url),'utf8');
const context=vm.createContext({Date,Intl,Map,Set,console,crypto:{randomUUID:()=> '56e185ce-36b0-47ee-befa-9fe98d5525cb'},localStorage:{getItem:()=>null,setItem:()=>{}}});
vm.runInContext(source.replace(/\ninit\(\);\s*$/,''),context);
vm.runInContext('recommendations=new PaperRecommendations(""); recommendations.ready=true;',context);
const row=vm.runInContext('paperRow',context);
const paper={id:'2610.18806',title:'A & B',url:'https://arxiv.org/abs/2610.18806',authors:['A. One','B. Two','C. Three','D. Four'],source:'arXiv',journals:[],publication_date:'2026-10-15',first_seen:'2026-10-15T01:00:00Z',variants:[],abstract:'Original abstract. Full final sentence. <script>',intro_zh:'DO NOT DISPLAY',intro_en:'DO NOT DISPLAY',fit_score:90};
const html=row(paper);
assert.ok(html.includes('Original abstract. Full final sentence. &lt;script&gt;'));
assert.ok(html.includes('<details class="abstract"><summary>Abstract</summary>'));
assert.ok(!html.includes('<details open'));
assert.ok(!html.includes('DO NOT DISPLAY'));
assert.ok(!html.includes('fit-score'));
assert.ok(html.includes('A. One, B. Two, C. Three, et al.'));
const catalog=JSON.parse(fs.readFileSync(new URL('./catalog.json',import.meta.url)));
for(const p of catalog.papers)assert.equal(Object.keys(p).some(k=>k.startsWith('intro_')),false);
console.log('Compact list: original full abstract, closed by default, escaped text and no generated summaries passed.');
