import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context=vm.createContext({Date,Intl,Map,Set,console});
const app=fs.readFileSync(new URL('./app.js',import.meta.url),'utf8');
vm.runInContext(app.replace(/\ninit\(\);\s*$/,''),context);
const authors=vm.runInContext('paperAuthors',context);
const network=fs.readFileSync(new URL('./network.js',import.meta.url),'utf8');
const label=vm.runInContext(network.match(/^const personLabel=.*$/m)[0]+'\npersonLabel',vm.createContext({}));
const verified={name:'Lile Wang',name_zh:'王力乐',name_source:'https://doi.org/10.3847/1538-4357/ae986b'};
assert.equal(authors({authors:['Lile Wang'],author_affiliations:[verified]})[0],'王力乐 · Lile Wang');
assert.equal(label(verified),'王力乐 · Lile Wang');
assert.equal(authors({authors:['Lile Wang'],author_affiliations:[{...verified,name_source:null}]})[0],'Lile Wang');
assert.equal(label({...verified,name_source:null}),'Lile Wang');
assert.equal(authors({authors:['Another Wang'],author_affiliations:[verified]})[0],'Another Wang');
assert.equal(authors({authors:['Lile Wang'],author_affiliations:[verified,{...verified,name_zh:'另一个姓名'}]})[0],'Lile Wang');
assert.equal(authors({author_affiliations:[verified]})[0],'王力乐 · Lile Wang');
assert.equal(label({name:'王力乐',name_zh:'王力乐',name_source:verified.name_source}),'王力乐');
const catalog=JSON.parse(fs.readFileSync(new URL('./catalog.json',import.meta.url)));
const papers=catalog.papers.filter(p=>authors(p).some(n=>n.includes(' · ')));
assert.ok(papers.length>0);
for(const expected of ['王力乐 · Lile Wang','范辰碩 · Chen-Shuo Fan'])assert.ok(papers.some(p=>authors(p).includes(expected)),expected);
console.log(`Verified bilingual author display: ${papers.length} existing papers; publisher and ORCID examples, ambiguous/missing evidence fallbacks passed.`);
